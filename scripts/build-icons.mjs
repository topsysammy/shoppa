// Converts the Figma "Icons" frame export (design/icons-frame.svg, node 110:2)
// into an inline-SVG icon module. Each icon is a 24x24 cell; positions come from
// the Figma metadata for the frame. Stroke colour becomes currentColor so icons
// follow text colour in light and dark themes.
import { readFileSync, writeFileSync } from 'node:fs';

const svg = readFileSync('design/icons-frame.svg', 'utf8');

// name -> [x, y] inside the Icons frame (Figma metadata, page "Foundations & Components")
const cells = {
  home: [24, 24], list: [64, 24], plus: [104, 24], users: [144, 24], user: [184, 24],
  bell: [224, 24], search: [264, 24], back: [304, 24], 'chevron-right': [344, 24],
  'chevron-down': [384, 24], close: [424, 24], more: [464, 24], share: [504, 24],
  bag: [544, 24], 'bag-check': [584, 24], comment: [624, 24], check: [664, 24], trash: [704, 24],
  edit: [24, 64], link: [64, 64], mail: [104, 64], whatsapp: [144, 64], clock: [184, 64],
  refresh: [224, 64], 'wifi-off': [264, 64], alert: [304, 64], shield: [344, 64], help: [384, 64],
  moon: [424, 64], logout: [464, 64], ruler: [504, 64], settings: [544, 64], filter: [584, 64],
  gift: [624, 64], leaf: [664, 64], box: [704, 64], broom: [24, 104], lock: [64, 104],
  camera: [104, 104], external: [144, 104], 'arrow-right': [184, 104], minus: [224, 104],
  eye: [264, 104], apple: [304, 104],
};

const out = {};
for (const [name, [x, y]] of Object.entries(cells)) {
  const start = svg.indexOf(`<g id="icon/${name}">`);
  if (start < 0) throw new Error(`icon/${name} not found`);
  const next = svg.indexOf('<g id="icon/', start + 10);
  const block = svg.slice(start, next < 0 ? svg.lastIndexOf('</g>') : next);
  const paths = [...block.matchAll(/<path [^>]*?\sd="([^"]+)"[^>]*?stroke-width="([\d.]+)"/g)].map(
    (m) => ({ d: translate(m[1], -x, -y), w: Number(m[2]) }),
  );
  if (!paths.length) throw new Error(`icon/${name} has no paths`);
  out[name] = paths;
}

// Shift absolute path coordinates. Figma exports only absolute commands
// (M L H V C Z), so every number pair is an x,y except H (x) and V (y).
function translate(d, dx, dy) {
  return d.replace(/([MLHVCZ])([^MLHVCZ]*)/g, (_, cmd, args) => {
    const nums = (args.match(/-?\d*\.?\d+(?:e-?\d+)?/g) || []).map(Number);
    const r = (n) => +n.toFixed(3);
    let shifted;
    if (cmd === 'H') shifted = nums.map((n) => r(n + dx));
    else if (cmd === 'V') shifted = nums.map((n) => r(n + dy));
    else shifted = nums.map((n, i) => r(n + (i % 2 === 0 ? dx : dy)));
    return cmd + shifted.join(' ');
  });
}

const names = Object.keys(out);
const body = names
  .map((n) => `  '${n}': [${out[n].map((p) => `[${JSON.stringify(p.d)}, ${p.w}]`).join(', ')}],`)
  .join('\n');
writeFileSync(
  'src/components/icons/icon-paths.ts',
  `// Generated by scripts/build-icons.mjs from Figma node 110:2. Do not edit by hand.\n` +
    `export const iconPaths = {\n${body}\n} as const satisfies Record<string, ReadonlyArray<readonly [string, number]>>;\n\n` +
    `export type IconName = keyof typeof iconPaths;\n`,
);
console.log(`Wrote ${names.length} icons`);
